"""Fit the skill demand curves on the bundled map pool and write them as a constant table.

Usage: python backend/tools/fit_demand_curves.py [POOL] [OUT]
Defaults: the bundled pool (osu_coach/maps/data/pool.json.gz) and osu_coach/profile/domain/demand_table.py.
Run it again after the pool is rebuilt; backend/tests/profile/test_demand.py fails while the table is stale.
"""

import sys
from pathlib import Path

from osu_coach.maps.repository import POOL_PATH, load_pool
from osu_coach.profile.domain.demand import fit_demand

OUT = Path(__file__).resolve().parents[1] / "src" / "osu_coach" / "profile" / "domain" / "demand_table.py"


def _numbers(values: list[float], indent: str, per_line: int = 12) -> list[str]:
    rows = [values[i : i + per_line] for i in range(0, len(values), per_line)]
    return [indent + ", ".join(f"{v:g}" for v in row) + "," for row in rows]


def render(fit: dict) -> str:
    lines = [
        '"""Skill demand curves fitted on the bundled map pool: generated by backend/tools/fit_demand_curves.py, do not',
        f"edit. ``DEMAND``: log2 demand of typical maps of each star rating in ``GRID``, relative to 1★. Fitted on {fit['maps']}",
        'maps, no mod and DT."""',
        "",
        "# fmt: off",
        "GRID = [",
        *_numbers(fit["grid"], "    "),
        "]",
    ]
    lines += ["", "DEMAND = {"]
    for key, values in fit["demand"].items():
        lines += [f'    "{key}": [', *_numbers(values, "        "), "    ],"]
    lines.append("}")
    lines += ["# fmt: on", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    pool = load_pool(argv[0] if argv else POOL_PATH)
    out = Path(argv[1]) if len(argv) > 1 else OUT
    out.write_text(render(fit_demand(pool)), encoding="utf-8")
    print(f"{out}: {len(pool)} maps")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
