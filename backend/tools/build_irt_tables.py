"""Fit the Star-Scale IRT anchor curves on the bundled map pool and write them as a constant table.

Usage: python backend/tools/build_irt_tables.py [POOL] [OUT]
Defaults: the bundled pool (osu_coach/infra/data/pool.json.gz) and osu_coach/domain/player/engines/irt/tables.py.
Run it again after the pool is rebuilt (backend/tests/domain/player/engines/irt/test_tables.py fails while the table is
stale), and raise ANCHOR_VERSION when the numbers change: stored play summaries are then made again.
"""

import re
import sys
from pathlib import Path

from osu_coach.domain.player.engines.irt.anchors import fit_anchors
from osu_coach.infra.map_pool import POOL_PATH, load_pool

OUT = Path(__file__).resolve().parents[1] / "src" / "osu_coach" / "domain" / "player" / "engines" / "irt" / "tables.py"


def _numbers(values: list[float], indent: str, per_line: int = 10) -> list[str]:
    rows = [values[i : i + per_line] for i in range(0, len(values), per_line)]
    return [indent + ", ".join(f"{v:g}" for v in row) + "," for row in rows]


def _version(out: Path) -> int:
    text = out.read_text(encoding="utf-8") if out.exists() else ""
    found = re.search(r"^ANCHOR_VERSION = (\d+)", text, re.M)
    return int(found.group(1)) if found else 1


def render(fit: dict, version: int) -> str:
    lines = [
        '"""Star-Scale IRT anchors fitted on the bundled map pool: generated by backend/tools/build_irt_tables.py, do',
        f"not edit (raise ANCHOR_VERSION by hand when the numbers change). Fitted on {fit['maps']} maps, no mod and DT.",
        "",
        "``ANCHORS[k]``: the raw demand of skill k (log2 aim / speed rating, -log2 preempt and 300 window in ms, log2",
        "slider speed in circle widths per second) of the median map at every knot of ``anchors.GRID``.",
        '``NATURAL[k]``: the same in natural units (``anchors.UNITS``)."""',
        "",
        f"ANCHOR_VERSION = {version}",
        "",
        "# fmt: off",
        "ANCHORS = {",
    ]
    for key, values in fit["anchors"].items():
        lines += [f'    "{key}": [', *_numbers(values, "        "), "    ],"]
    lines += ["}", "", "NATURAL = {"]
    for key, values in fit["natural"].items():
        lines += [f'    "{key}": [', *_numbers(values, "        "), "    ],"]
    lines += ["}", "# fmt: on", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    pool = load_pool(argv[0] if argv else POOL_PATH)
    out = Path(argv[1]) if len(argv) > 1 else OUT
    out.write_text(render(fit_anchors(pool), _version(out)), encoding="utf-8")
    print(f"{out}: {len(pool)} maps")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
